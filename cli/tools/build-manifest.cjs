#!/usr/bin/env node
/* Regenerates cli/manifest.js: the exact files and byte counts aegis-init writes for every
 * preset × mode × fonts combination, taken from the CLI's own --dry-run --json output.
 * The CLI page uses it to show real output without running anything in the browser.
 *
 *   node cli/tools/build-manifest.cjs          # write cli/manifest.js
 *   node cli/tools/build-manifest.cjs --check  # exit 1 if cli/manifest.js is stale
 */
'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const CLI = path.join(ROOT, 'cli', 'aegis-init.js');
const OUT = path.join(ROOT, 'cli', 'manifest.js');
const MODES = ['light', 'dark', 'auto'];

function dryRun(cwd, args) {
  const out = execFileSync(process.execPath, [CLI, ...args, '--out=./app', '--dry-run', '--json'], { cwd, encoding: 'utf8' });
  return JSON.parse(out);
}

function build() {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), 'aegis-manifest-'));
  try {
    const index = JSON.parse(fs.readFileSync(path.join(ROOT, 'presets', 'tokens', 'index.json'), 'utf8'));
    const { ALIASES, OUTPUT_FILES, VERSION } = require(CLI);
    const presets = {};
    for (const p of index.presets) {
      const id = p.id;
      const base = dryRun(cwd, [`--preset=${id}`]);
      const sizes = {};
      for (const mode of MODES) {
        for (const fonts of [true, false]) {
          const r = dryRun(cwd, [`--preset=${id}`, `--mode=${mode}`].concat(fonts ? [] : ['--no-fonts']));
          sizes[mode + (fonts ? '' : '+nofonts')] = r.files.map((f) => f.bytes);
        }
      }
      presets[id] = {
        name: base.name,
        defaultMode: base.mode,
        aliases: Object.keys(ALIASES).filter((a) => ALIASES[a] === id),
        sizes,
      };
    }
    return { version: VERSION, files: OUTPUT_FILES.slice(), presets };
  } finally {
    fs.rmSync(cwd, { recursive: true, force: true });
  }
}

function render(data) {
  return '/* Generated by cli/tools/build-manifest.cjs from aegis-init --dry-run --json. Do not edit:\n' +
    ' * run `node cli/tools/build-manifest.cjs` after changing the CLI or rebuilding presets. */\n' +
    'window.AegisCliManifest = ' + JSON.stringify(data) + ';\n';
}

if (require.main === module) {
  const text = render(build());
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) { console.error('cli/manifest.js is stale. Run: node cli/tools/build-manifest.cjs'); process.exit(1); }
    console.log('cli/manifest.js is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('Wrote ' + path.relative(process.cwd(), OUT));
  }
}

module.exports = { build, render };
