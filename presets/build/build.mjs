#!/usr/bin/env node
// AegisUI preset build. Zero dependencies — run with `node presets/build/build.mjs [--strict]`.
//
//   presets/themes/*.mjs  ──► presets/tokens/<id>.json   (AegisUI token JSON — Figma plugin input)
//                         ──► presets/css/<id>.css        (CSS custom properties, light + dark)
//                         ──► presets/aegis-presets.css   (all themes, no font imports)
//                         ──► presets/aegis-presets.js    (runtime registry: window.AegisPresets / CommonJS)
//                         ──► figma-plugin/ui.html        (built-in presets injected between markers)

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { generate, MODES } from './generate.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const presetsDir = path.resolve(here, '..');
const rootDir = path.resolve(presetsDir, '..');
const strict = process.argv.includes('--strict');

/* ----------------------------------------------------------- CSS emitter */

function getPath(obj, p) {
  return p.split('.').reduce((o, k) => (o ? o[k] : undefined), obj);
}

function walk(node, fn, trail = []) {
  if (node && typeof node === 'object' && ('$value' in node || '$modes' in node)) return fn(node, trail);
  for (const [k, v] of Object.entries(node)) if (v && typeof v === 'object') walk(v, fn, [...trail, k]);
}

function cssValue(tokens, type, value) {
  if (typeof value === 'string' && value.startsWith('{')) {
    const target = getPath(tokens, value.slice(1, -1));
    if (!target) throw new Error('Unresolved alias ' + value);
    return `var(${target.$extensions.aegis.cssVar})`;
  }
  switch (type) {
    case 'dimension': return `${value}px`;
    case 'duration': return `${value}ms`;
    case 'cubicBezier': return `cubic-bezier(${value.join(', ')})`;
    case 'number': return `${value}em`;
    case 'shadow':
      if (typeof value === 'string') return value;
      return value.length
        ? value.map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.spread}px ${s.color}`).join(', ')
        : 'none';
    default: return String(value);
  }
}

export function emitCss(doc, { withFonts = true } = {}) {
  const { tokens, meta } = doc;
  const sel = `[data-aegis-theme="${meta.id}"]`;
  const base = [];
  const moded = Object.fromEntries(MODES.map((m) => [m, []]));
  const section = (title) => base.push(`\n  /* ${title} */`);

  let lastGroup = '';
  walk(tokens, (tok, trail) => {
    const group = trail.slice(0, 2).join('.');
    const v = tok.$extensions.aegis.cssVar;
    if (tok.$modes) {
      for (const m of MODES) moded[m].push(`  ${v}: ${cssValue(tokens, tok.$type, tok.$modes[m])};`);
      return;
    }
    if (group !== lastGroup && trail[0] !== 'component') { section(group); lastGroup = group; }
    if (trail[0] === 'component' && lastGroup !== 'component.' + trail[1]) { section('component · ' + trail[1]); lastGroup = 'component.' + trail[1]; }
    if (tok.$type === 'fontFamily') return base.push(`  ${v}: ${tok.$extensions.aegis.stack};`);
    if (tok.$type === 'typography') {
      const t = tok.$value;
      const fam = cssValue(tokens, 'fontFamily', t.fontFamily);
      base.push(
        `  ${v}-family: ${fam};`,
        `  ${v}-size: ${t.fontSize}px;`,
        `  ${v}-line: ${t.lineHeight}px;`,
        `  ${v}-weight: ${t.fontWeight};`,
        `  ${v}-tracking: ${t.letterSpacing}em;`,
        `  ${v}-transform: ${t.textTransform};`,
        `  ${v}-features: ${t.fontFeatures ? t.fontFeatures.map((f) => `"${f}"`).join(', ') : 'normal'};`,
        `  ${v}: ${t.fontWeight} ${t.fontSize}px/${t.lineHeight}px ${fam};`,
      );
      return;
    }
    if (trail[0] === 'component' && /text-style$/.test(trail[2])) {
      // Named text-style reference → usable as `font: var(--aegis-button-text-style)`.
      return base.push(`  ${v}: var(--aegis-text-${tok.$value});`);
    }
    base.push(`  ${v}: ${cssValue(tokens, tok.$type, tok.$value)};`);
  });

  const header = `/*!\n * AegisUI preset · ${meta.name} (${meta.id})\n * ${meta.description}\n * Generated by presets/build/build.mjs — edit presets/themes/${meta.id}.mjs instead.\n * Usage: <html data-aegis-theme="${meta.id}" data-aegis-mode="light|dark|auto">\n */\n`;
  const fonts = withFonts ? `@import url("${meta.fonts.googleFontsUrl}");\n\n` : '';
  return (
    header + fonts +
    `${sel} {\n  color-scheme: light;\n${base.join('\n')}\n\n  /* semantic · light */\n${moded.light.join('\n')}\n}\n\n` +
    `${sel}[data-aegis-mode="dark"] {\n  color-scheme: dark;\n${moded.dark.join('\n')}\n}\n\n` +
    `@media (prefers-color-scheme: dark) {\n  ${sel}[data-aegis-mode="auto"] {\n    color-scheme: dark;\n${moded.dark.map((l) => '  ' + l).join('\n')}\n  }\n}\n`
  );
}

/* --------------------------------------------------------- runtime JS */

function emitRegistry(docs) {
  const data = JSON.stringify(Object.fromEntries(docs.map((d) => [d.meta.id, d])));
  return `/*! AegisUI preset registry — generated by presets/build/build.mjs. Do not edit. */
(function (root, factory) {
  var api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.AegisPresets = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  var PRESETS = ${data};
  var ORDER = ${JSON.stringify(docs.map((d) => d.meta.id))};

  function get(id) {
    if (!PRESETS[id]) throw new Error('AegisPresets: unknown preset "' + id + '"');
    return PRESETS[id];
  }
  function list() {
    return ORDER.map(function (id) { return PRESETS[id].meta; });
  }
  /** Deep copy of the AegisUI token JSON — this is what the Figma plugin imports. */
  function toJSON(id, pretty) {
    return JSON.stringify(get(id), null, pretty === false ? 0 : 2);
  }
  /** Inject the preset's Google Fonts stylesheet once. */
  function loadFonts(id, doc) {
    doc = doc || (typeof document !== 'undefined' ? document : null);
    if (!doc) return;
    var linkId = 'aegis-fonts-' + id;
    if (doc.getElementById(linkId)) return;
    var link = doc.createElement('link');
    link.id = linkId;
    link.rel = 'stylesheet';
    link.href = get(id).meta.fonts.googleFontsUrl;
    doc.head.appendChild(link);
  }
  /**
   * Apply a preset to an element (default <html>).
   * mode: 'light' | 'dark' | 'auto' | undefined (preset default).
   * Requires aegis-presets.css (or css/<id>.css) to be loaded.
   */
  function apply(id, opts) {
    opts = opts || {};
    var el = opts.target || document.documentElement;
    var meta = get(id).meta;
    el.setAttribute('data-aegis-theme', id);
    el.setAttribute('data-aegis-mode', opts.mode || meta.defaultMode);
    if (opts.loadFonts !== false) loadFonts(id, el.ownerDocument);
    return meta;
  }
  /** Resolve an alias like "{semantic.color.brand.default}" to a concrete value for a mode. */
  function resolve(id, ref, mode) {
    var tokens = get(id).tokens;
    var seen = 0;
    var value = ref;
    while (typeof value === 'string' && value.charAt(0) === '{' && seen++ < 16) {
      var node = value.slice(1, -1).split('.').reduce(function (o, k) { return o ? o[k] : undefined; }, tokens);
      if (!node) return undefined;
      value = node.$modes ? node.$modes[mode || 'light'] : node.$value;
    }
    return value;
  }
  return { version: '1.0.0', list: list, get: get, toJSON: toJSON, apply: apply, loadFonts: loadFonts, resolve: resolve, ids: ORDER.slice() };
});
`;
}

/* --------------------------------------------------------------- main */

async function main() {
  const themeDir = path.join(presetsDir, 'themes');
  const files = (await readdir(themeDir)).filter((f) => f.endsWith('.mjs')).sort();
  const defs = [];
  for (const f of files) defs.push((await import(pathToFileURL(path.join(themeDir, f)).href)).default);
  defs.sort((a, b) => (a.order ?? 99) - (b.order ?? 99));

  await mkdir(path.join(presetsDir, 'tokens'), { recursive: true });
  await mkdir(path.join(presetsDir, 'css'), { recursive: true });

  const docs = [];
  let failures = 0;
  for (const def of defs) {
    const doc = generate(def);
    docs.push(doc);
    await writeFile(path.join(presetsDir, 'tokens', `${def.id}.json`), JSON.stringify(doc, null, 2) + '\n');
    await writeFile(path.join(presetsDir, 'css', `${def.id}.css`), emitCss(doc));
    const fails = doc.a11y.checks.filter((c) => !c.pass);
    failures += fails.length;
    const flag = fails.length ? '✗' : '✓';
    console.log(`${flag} ${def.id.padEnd(22)} ${doc.a11y.target}  ${doc.a11y.checks.length - fails.length}/${doc.a11y.checks.length} contrast checks · ${doc.a11y.adjustments.length} auto-adjusted`);
    for (const f of fails) console.log(`    ✗ [${f.mode}] ${f.fg} on ${f.bg}: ${f.ratio} < ${f.min}`);
  }

  const bundle = `/*! AegisUI presets bundle — ${docs.length} themes. Generated; do not edit.\n * Fonts are not imported here; call AegisPresets.loadFonts(id) or link meta.fonts.googleFontsUrl. */\n\n` +
    docs.map((d) => emitCss(d, { withFonts: false }).replace(/^\/\*![\s\S]*?\*\/\n/, `/* ── ${d.meta.name} ── */\n`)).join('\n');
  await writeFile(path.join(presetsDir, 'aegis-presets.css'), bundle);
  await writeFile(path.join(presetsDir, 'aegis-presets.js'), emitRegistry(docs));
  await writeFile(
    path.join(presetsDir, 'tokens', 'index.json'),
    JSON.stringify({ aegis: docs[0].aegis, presets: docs.map((d) => ({ ...d.meta, file: `${d.meta.id}.json` })) }, null, 2) + '\n',
  );

  // Inject built-in presets into the Figma plugin UI.
  const uiPath = path.join(rootDir, 'figma-plugin', 'ui.html');
  try {
    const ui = await readFile(uiPath, 'utf8');
    const start = '/* AEGIS:PRESETS:START */';
    const end = '/* AEGIS:PRESETS:END */';
    const a = ui.indexOf(start);
    const b = ui.indexOf(end);
    if (a >= 0 && b > a) {
      const payload = `var AEGIS_BUILTIN_PRESETS = ${JSON.stringify(Object.fromEntries(docs.map((d) => [d.meta.id, d])))};`;
      await writeFile(uiPath, ui.slice(0, a + start.length) + '\n' + payload + '\n' + ui.slice(b));
      console.log(`→ injected ${docs.length} presets into figma-plugin/ui.html`);
    }
  } catch (e) {
    if (e.code !== 'ENOENT') throw e;
  }

  console.log(`\nBuilt ${docs.length} presets → presets/tokens, presets/css, aegis-presets.{css,js}`);
  if (failures) {
    console.log(`${failures} contrast check(s) failed.`);
    if (strict) process.exit(1);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
